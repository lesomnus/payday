package pdcli

import (
	"os"
	"path/filepath"
	"strings"
	"testing"

	"github.com/stretchr/testify/require"

	"github.com/lesomnus/payday/internal/pdgen"
)

// What `pd doctor` asks of an app with a column of payday's that an earlier
// build stored under another name (payday#196): that its migration moves it
// first -- read off the app's own Go, so each case is a few lines of it.

var dateRead = pdgen.ColumnRename{Table: "notificationreceiptrecord", From: "data_read", To: "date_read"}

// renamed is what the doctor says of an app of `files` whose schema has `vs`.
func renamed(t *testing.T, files map[string]string, vs ...pdgen.ColumnRename) string {
	t.Helper()
	x := require.New(t)

	root := t.TempDir()
	for name, src := range files {
		p := filepath.Join(root, name)
		x.NoError(os.MkdirAll(filepath.Dir(p), 0o755))
		x.NoError(os.WriteFile(p, []byte(src), 0o644))
	}

	l := Layout{Root: root, Work: root, Module: "github.com/acme/thing"}
	said := []string{}
	for _, v := range doctorRenames(l, vs) {
		said = append(said, v.String())
	}

	return strings.Join(said, "\n")
}

// What `pd new` writes, and so what every app made since does.
const migrating = `package cli

import (
	"context"

	payrename "github.com/lesomnus/payday/rename"

	"github.com/acme/thing/cmd"
	"github.com/acme/thing/server/pd"
)

func Migrate(ctx context.Context, s *cmd.Server) error {
	if err := payrename.Columns(ctx, s.Db, s.Dialect, pd.ColumnRenames); err != nil {
		return err
	}
	return nil
}
`

func TestAMigrationThatMovesARenamedColumnIsWell(t *testing.T) {
	require.Empty(t, renamed(t, map[string]string{"cli/cli.go": migrating}, dateRead))

	// And an app that has none of payday's renamed columns is asked nothing.
	require.Empty(t, renamed(t, map[string]string{"cli/cli.go": "package cli\n"}))
}

// TestAMigrationThatDoesNotMoveARenamedColumnIsSaid: the migration would add
// the column empty beside the old one, which nothing reports.
func TestAMigrationThatDoesNotMoveARenamedColumnIsSaid(t *testing.T) {
	x := require.New(t)

	v := renamed(t, map[string]string{"cli/cli.go": `package cli

import "github.com/lesomnus/payday/rename"

var _ = rename.Indexes
`}, dateRead)
	x.Contains(v, "rename.Columns")
	x.Contains(v, "notificationreceiptrecord.date_read, which an earlier build called data_read")

	// A test says nothing about what the app migrates with, and neither does
	// what a generator wrote.
	x.NotEmpty(renamed(t, map[string]string{"cli/cli_test.go": strings.Replace(migrating, "package cli", "package cli_test", 1)}, dateRead))
	x.NotEmpty(renamed(t, map[string]string{"cli/cli.g.go": "// Code generated by hand. DO NOT EDIT.\n\n" + migrating}, dateRead))

	// Nor a function of the same name of another package.
	x.NotEmpty(renamed(t, map[string]string{"cli/cli.go": `package cli

import "example.com/rename"

var _ = rename.Columns(nil, nil, "", nil)
`}, dateRead))
}
