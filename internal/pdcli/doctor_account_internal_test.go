// What `pd doctor` asks of an app whose holders are memberships of accounts
// (payday#184): that each method an account calls as itself says what it
// reads, and that a resolver serves a call as one -- read off the app's own
// Go, so each case is a few lines of it in a module of its own.

// accounted is what the doctor says of an app of `files` whose schema marks
// `methods` an account's own, or of one that declares no accounts at all.
func accounted(t *testing.T, accounts bool, files map[string]string, methods ...pdgen.AccountMethod) string {
	t.Helper()
	x := require.New(t)

	root := t.TempDir()
	for name, src := range files {
		p := filepath.Join(root, name)
		x.NoError(os.MkdirAll(filepath.Dir(p), 0o755))
		x.NoError(os.WriteFile(p, []byte(src), 0o644))
	}

	s := &pdgen.Schema{}
	if accounts {
		s.Accounts = &pdgen.Accounts{Methods: methods}
	}

	l := Layout{Root: root, Work: root, Module: "github.com/acme/thing"}
	said := []string{}
	for _, v := range doctorAccounts(l, s) {
		said = append(said, v.String())
	}

	return strings.Join(said, "\n")
}

var accept = pdgen.AccountMethod{
	Full:    "/app.InvitationService/Accept",
	Service: "InvitationService",
	Method:  "Accept",
	Const:   "InvitationService_Accept_FullMethodName",
}

var deny = pdgen.AccountMethod{
	Full:    "/app.InvitationService/Deny",
	Service: "InvitationService",
	Method:  "Deny",
	Const:   "InvitationService_Deny_FullMethodName",
}

const resolving = `package cmd

import "github.com/acme/thing/server/pd"

func resolver() any {
	return pd.AccountResolver(nil, "acme-workspace", nil, nil)
}
`

const reading = `package domain

import (
	"context"

	app "github.com/acme/thing"
	"github.com/acme/thing/server/pd"
)

func accept(ctx context.Context) error {
	_, err := pd.AccountReads(ctx, app.InvitationService_Accept_FullMethodName, pd.Reads{})
	return err
}

func deny(ctx context.Context) error {
	_, err := pd.AccountReads(ctx, "/app.InvitationService/Deny", pd.Reads{})
	return err
}
`

// TestTheAccountsTheGuideWiresAreWell, which is the half that fails if this
// learns to complain about something ordinary.
func TestTheAccountsTheGuideWiresAreWell(t *testing.T) {
	require.Empty(t, accounted(t, true, map[string]string{"cmd/serve.go": resolving, "domain/invitation.go": reading}, accept, deny))

	// By the runtime's own Resolver, written out.
	require.Empty(t, accounted(t, true, map[string]string{
		"cmd/serve.go": `package cmd

import "github.com/lesomnus/payday/account"

var r = account.Resolver{Header: "acme-workspace"}
`,
		"domain/invitation.go": reading,
	}, accept))

	// And an app that declares none is asked nothing.
	require.Empty(t, accounted(t, false, map[string]string{"cmd/serve.go": "package cmd\n"}, accept))
}

// TestAnAccountsMethodThatDeclaresNothingIsSaid: it reads nothing through the
// walled servers, which is an empty answer and very likely a layer somebody
// forgot to finish.
func TestAnAccountsMethodThatDeclaresNothingIsSaid(t *testing.T) {
	x := require.New(t)

	v := accounted(t, true, map[string]string{"cmd/serve.go": resolving}, accept)
	x.Contains(v, "declare nothing they read")
	x.Contains(v, "/app.InvitationService/Accept")
	x.Contains(v, "app.InvitationService_Accept_FullMethodName")

	// One of two.
	v = accounted(t, true, map[string]string{"cmd/serve.go": resolving, "domain/invitation.go": `package domain

import (
	"context"

	app "github.com/acme/thing"
	"github.com/acme/thing/server/pd"
)

func accept(ctx context.Context) error {
	_, err := pd.AccountReads(ctx, app.InvitationService_Accept_FullMethodName, pd.Reads{})
	return err
}
`}, accept, deny)
	x.Contains(v, "declare nothing they read")
	x.Contains(v, "/app.InvitationService/Deny")
	x.NotContains(v, "/app.InvitationService/Accept")

	// A declaration in a test is not the app's, nor one in a generated file.
	for _, at := range []string{"domain/invitation_test.go", "domain/invitation.g.go"} {
		src := reading
		if strings.HasSuffix(at, ".g.go") {
			src = "// Code generated by hand for a test. DO NOT EDIT.\n\n" + reading
		}
		v = accounted(t, true, map[string]string{"cmd/serve.go": resolving, at: src}, accept)
		x.Contains(v, "declare nothing they read", at)
	}
}

// TestAnAppWithAccountsAndNoResolverIsSaid: every call an account makes is
// refused, since its credential names nobody who is here.
func TestAnAppWithAccountsAndNoResolverIsSaid(t *testing.T) {
	x := require.New(t)

	v := accounted(t, true, map[string]string{"domain/invitation.go": reading}, accept, deny)
	x.Contains(v, "no resolver serves a call as one")
	x.NotContains(v, "declare nothing they read")

	// And not by a Resolver of some other package.
	v = accounted(t, true, map[string]string{"domain/invitation.go": reading, "cmd/serve.go": `package cmd

import "github.com/lesomnus/payday/auth"

var r = auth.ResolverFunc(nil)
`}, accept, deny)
	x.Contains(v, "no resolver serves a call as one")
}
