// The paydays a module proxy of these tests' own serves, as payday's own is
// served: the one an app is on, which has `batch`; the one it moves to, which
// went on without it; and v0.1.0, a release that has it -- to the go command
// the newest payday, and `latest`, for as long as no later version publishes
// the retraction of it.
const (
	paydayWas = "v0.0.0-20261001000000-0123456789ab"
	paydayTo  = "v0.0.0-20261111000000-ba9876543210"
	paydayTag = "v0.1.0"
)

// paydays serves those from a proxy of files and points the go command at it,
// with a module cache of its own: the real payday at those versions is not
// these. With `retracted` it serves v0.1.1 as well, retracting v0.1.0 and
// itself, as payday's go.mod says and its proxy has not been told.
func paydays(t *testing.T, retracted bool) {
	t.Helper()
	x := require.New(t)

	px := t.TempDir()
	at := filepath.Join(px, "github.com", "lesomnus", "payday", "@v")
	x.NoError(os.MkdirAll(at, 0o755))

	publish := func(v string, when string, gomod string, pkgs ...string) {
		src := t.TempDir()
		x.NoError(os.WriteFile(filepath.Join(src, "go.mod"), []byte(gomod), 0o644))
		for _, p := range pkgs {
			x.NoError(os.MkdirAll(filepath.Join(src, p), 0o755))
			x.NoError(os.WriteFile(filepath.Join(src, p, p+".go"), []byte("package "+p+"\n\n// Is says it is here.\nconst Is = true\n"), 0o644))
		}

		var b bytes.Buffer
		x.NoError(zip.CreateFromDir(&b, module.Version{Path: "github.com/lesomnus/payday", Version: v}, src))
		x.NoError(os.WriteFile(filepath.Join(at, v+".zip"), b.Bytes(), 0o644))
		x.NoError(os.WriteFile(filepath.Join(at, v+".mod"), []byte(gomod), 0o644))
		info, err := json.Marshal(map[string]string{"Version": v, "Time": when})
		x.NoError(err)
		x.NoError(os.WriteFile(filepath.Join(at, v+".info"), info, 0o644))
	}

	gomod := "module github.com/lesomnus/payday\n\ngo 1.25\n"
	publish(paydayWas, "2026-10-01T00:00:00Z", gomod, "batch", "resource")
	publish(paydayTo, "2026-11-11T00:00:00Z", gomod, "resource")
	publish(paydayTag, "2026-10-29T16:44:42Z", gomod, "batch", "resource")
	list := paydayTag + "\n"
	if retracted {
		publish("v0.1.1", "2026-11-12T00:00:00Z", gomod+"\nretract (\n\tv0.1.1\n\tv0.1.0\n)\n", "resource")
		list += "v0.1.1\n"
	}
	x.NoError(os.WriteFile(filepath.Join(at, "list"), []byte(list), 0o644))

	for k, v := range map[string]string{
		"GOPROXY":     "file://" + filepath.ToSlash(px),
		"GOSUMDB":     "off",
		"GONOSUMDB":   "",
		"GOPRIVATE":   "",
		"GONOPROXY":   "",
		"GOINSECURE":  "",
		"GOMODCACHE":  t.TempDir(),
		"GOFLAGS":     "-modcacherw",
		"GOWORK":      "off",
		"GOTOOLCHAIN": "local",
	} {
		t.Setenv(k, v)
	}
}

// moving is an app on paydayWas whose generated code imports `batch`, as the
// code a payday that had it generated does. `go`, for it, is the go command but
// for `go tool pd`, which stands in for the payday the app moves to: its
// generator writes the code again without the import, and its upgrade has
// nothing to move. It answers with what `go` was asked.
func moving(t *testing.T) (pdcli.Layout, func() []string) {
	t.Helper()
	x := require.New(t)

	root := app(t, "github.com/acme/thing")
	gen := filepath.Join(root, "gen", "pd.g.go")
	x.NoError(os.MkdirAll(filepath.Dir(gen), 0o755))
	x.NoError(os.WriteFile(gen, generated("batch", "resource"), 0o644))

	real, err := exec.LookPath("go")
	x.NoError(err)
	for _, args := range [][]string{{"get", "github.com/lesomnus/payday@" + paydayWas}, {"mod", "tidy"}} {
		cmd := exec.Command(real, args...)
		cmd.Dir = root
		out, err := cmd.CombinedOutput()
		x.NoError(err, string(out))
	}

	again := filepath.Join(t.TempDir(), "pd.g.go")
	x.NoError(os.WriteFile(again, generated("resource"), 0o644))

	dir := t.TempDir()
	log := filepath.Join(dir, "go.log")
	sh := "#!/bin/sh\n" +
		"echo \"$*\" >> " + log + "\n" +
		"if [ \"$1 $2\" = \"tool pd\" ]; then\n" +
		"  if [ \"$3\" = gen ]; then cp " + again + " " + gen + "; fi\n" +
		"  exit 0\n" +
		"fi\n" +
		"exec " + real + " \"$@\"\n"
	x.NoError(os.WriteFile(filepath.Join(dir, "go"), []byte(sh), 0o755))
	t.Setenv("PATH", dir+string(os.PathListSeparator)+os.Getenv("PATH"))

	l, err := pdcli.Discover(root)
	x.NoError(err)

	return l, func() []string {
		b, err := os.ReadFile(log)
		if os.IsNotExist(err) {
			return nil
		}
		x.NoError(err)
		return strings.Split(strings.TrimSpace(string(b)), "\n")
	}
}

// generated is a generated file that imports those packages of payday's.
func generated(pkgs ...string) []byte {
	b := "// Code generated by pd. DO NOT EDIT.\n\npackage gen\n\nimport (\n"
	for _, p := range pkgs {
		b += "\t\"github.com/lesomnus/payday/" + p + "\"\n"
	}
	b += ")\n\nvar _ = []bool{"
	for _, p := range pkgs {
		b += p + ".Is, "
	}

	return []byte(b + "}\n")
}

// requires is the payday the app's go.mod names, and its go.sum.
func requires(t *testing.T, l pdcli.Layout) (string, string) {
	t.Helper()
	x := require.New(t)

	b, err := os.ReadFile(filepath.Join(l.Root, "go.mod"))
	x.NoError(err)
	f, err := modfile.ParseLax("go.mod", b, nil)
	x.NoError(err)
	sum, err := os.ReadFile(filepath.Join(l.Root, "go.sum"))
	x.NoError(err)

	for _, r := range f.Require {
		if r.Mod.Path == "github.com/lesomnus/payday" {
			return r.Mod.Version, string(sum)
		}
	}

	return "", string(sum)
}

// TestAnUpgradeLandsOnThePaydayItMovesTo: the code an older payday generated
// imports what that payday had, and a payday that went on without a package
// of it -- `batch`, at #229 -- is still the one the app lands on.
//
// It was not. `go mod tidy` ran before the new payday wrote the code again,
// read the old code's import, and found the package in v0.1.0, the newest
// payday that has it: the app was moved there, months behind, and nothing
// said so. Reproduced with the go command and a proxy that serves what
// payday's serves.
func TestAnUpgradeLandsOnThePaydayItMovesTo(t *testing.T) {
	x := require.New(t)
	paydays(t, false)
	l, _ := moving(t)

	x.NoError(pdcli.Upgrade{Layout: l, Payday: paydayTo}.Run(context.Background()))

	v, sum := requires(t, l)
	x.Equal(paydayTo, v, "tidy moved the app onto the payday that still has what the old code imported")
	x.NotContains(sum, paydayTag)
	b, err := os.ReadFile(filepath.Join(l.Root, "gen", "pd.g.go"))
	x.NoError(err)
	x.Equal(generated("resource"), b, "the generator's, before tidy read it")
}

// TestAnUpgradeIsRefusedWhereItWouldNotLand: code no generator writes -- the
// app's own, a dependency generated with an older payday -- is not written
// again, and would move the app just as the generated code did. So it is
// named before tidy runs; tidy moving payday anyway puts go.mod and go.sum
// back; and a payday its module retracts is not landed on at all.
func TestAnUpgradeIsRefusedWhereItWouldNotLand(t *testing.T) {
	own := func(t *testing.T, l pdcli.Layout, constraint string) {
		t.Helper()
		x := require.New(t)

		dir := filepath.Join(l.Root, "own")
		x.NoError(os.MkdirAll(dir, 0o755))
		x.NoError(os.WriteFile(filepath.Join(dir, "own.go"), []byte("package own\n"), 0o644))
		x.NoError(os.WriteFile(filepath.Join(dir, "batch.go"),
			[]byte(constraint+"package own\n\nimport \"github.com/lesomnus/payday/batch\"\n\nvar _ = batch.Is\n"), 0o644))
	}

	t.Run("an import of the app's own", func(t *testing.T) {
		x := require.New(t)
		paydays(t, false)
		l, goes := moving(t)
		own(t, l, "")

		err := pdcli.Upgrade{Layout: l, Payday: paydayTo}.Run(context.Background())
		x.ErrorIs(err, pdcli.ErrPaydayLacks)
		x.ErrorContains(err, "github.com/lesomnus/payday/batch, imported by github.com/acme/thing/own (the app's own)")

		v, sum := requires(t, l)
		x.Equal(paydayTo, v, "where `go get` put it")
		x.NotContains(sum, paydayTag)
		x.NotContains(goes(), "mod tidy", "refused before tidy found it somewhere else")
	})

	t.Run("one behind a build constraint, which tidy reads and nothing else here does", func(t *testing.T) {
		x := require.New(t)
		paydays(t, false)
		l, goes := moving(t)
		own(t, l, "//go:build pdupgrade\n\n")

		err := pdcli.Upgrade{Layout: l, Payday: paydayTo}.Run(context.Background())
		x.ErrorIs(err, pdcli.ErrPaydayMoved)
		x.ErrorContains(err, "from "+paydayTo+" to "+paydayTag)

		v, sum := requires(t, l)
		x.Equal(paydayTo, v, "put back as `go get` left it")
		x.NotContains(sum, paydayTag)
		x.Contains(goes(), "mod tidy")
		x.NotContains(goes(), "tool pd upgrade "+l.Root, "and nothing after it ran")
	})

	t.Run("a payday its module retracts", func(t *testing.T) {
		x := require.New(t)
		paydays(t, true)
		l, goes := moving(t)
		_, was := requires(t, l)

		err := pdcli.Upgrade{Layout: l, Payday: paydayTag}.Run(context.Background())
		x.ErrorIs(err, pdcli.ErrPaydayRetracted)

		v, sum := requires(t, l)
		x.Equal(paydayWas, v, "go.mod as it was")
		x.Equal(was, sum, "and go.sum")
		x.NotContains(goes(), "tool pd gen "+l.Root, "and nothing generated with it")
	})
}
