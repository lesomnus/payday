package pdcli

import (
	"io/fs"
	"maps"
	"os"
	"path/filepath"
	"slices"
	"testing"

	"github.com/stretchr/testify/require"
)

// TestTheSweepEndsWhereTheModuleDoes.
//
// [sweep] takes the generated Go a generation did not write, and a directory
// with a go.mod of its own is another module: what is generated there is that
// module's, by some other generator (payday#189). The go.mod at the root of the
// walk is the app's own, and that one does not stop it -- an app at the root of
// its module is nearly every app.
//
// And [Gen.Check] reads the same list before a generation, so that whatever the
// sweep takes is a file it says is no longer generated.
func TestTheSweepEndsWhereTheModuleDoes(t *testing.T) {
	x := require.New(t)

	root := t.TempDir()

	const gen = "// Code generated by protoc-gen-go. DO NOT EDIT.\n\npackage thing\n"
	for name, v := range map[string]string{
		"go.mod": "module github.com/acme/thing\n\ngo 1.27.0\n",

		// This generation's, and one that says nothing of a generator.
		"thing.pb.go": gen,
		"hand.pb.go":  "package thing\n",

		// Where `go_package` used to put the messages, and further down: all
		// of it this module's, which is what the sweep is for.
		"old/thing.pb.go":       gen,
		"tools/thing.g.go":      gen,
		"tools/sub/thing.pb.go": gen,
		"tools/sub/thing.g.go":  gen,
		"tools/sub/doc.go":      "package sub\n",

		// Another module, at the top as levyan's API is, and one inside a
		// directory of this module.
		"api/go.mod":                "module github.com/acme/thing/api\n\ngo 1.25.0\n",
		"api/thing/v1/thing.pb.go":  gen,
		"tools/plugin/go.mod":       "module github.com/acme/plugin\n\ngo 1.25.0\n",
		"tools/plugin/plugin.pb.go": gen,
		"tools/plugin/sub/x.g.go":   gen,
	} {
		at := filepath.Join(root, name)
		x.NoError(os.MkdirAll(filepath.Dir(at), 0o755))
		x.NoError(os.WriteFile(at, []byte(v), 0o644))
	}

	t.Run("the check reads what the sweep would take", func(t *testing.T) {
		x := require.New(t)

		l := Layout{Root: root, Module: "github.com/acme/thing", Pkg: "github.com/acme/thing", ProtoPkg: ProtoPkgDefault}
		vs, err := Gen{Layout: l, Out: root}.hashes()
		x.NoError(err)

		// The messages where they are, by the pattern the check has always
		// read them by, and the rest by the sweep's. Not another module's.
		x.Equal([]string{
			"hand.pb.go",
			"old/thing.pb.go",
			"thing.pb.go",
			"tools/sub/thing.g.go",
			"tools/sub/thing.pb.go",
			"tools/thing.g.go",
		}, slices.Sorted(maps.Keys(vs)))
	})

	x.NoError(sweep(root, map[string]bool{"thing.pb.go": true}))

	var left []string
	x.NoError(filepath.WalkDir(root, func(p string, d fs.DirEntry, err error) error {
		if err != nil || d.IsDir() {
			return err
		}

		rel, err := filepath.Rel(root, p)
		left = append(left, filepath.ToSlash(rel))

		return err
	}))
	x.Equal([]string{
		"api/go.mod",
		"api/thing/v1/thing.pb.go",
		"go.mod",
		"hand.pb.go",
		"thing.pb.go",
		"tools/plugin/go.mod",
		"tools/plugin/plugin.pb.go",
		"tools/plugin/sub/x.g.go",
		"tools/sub/doc.go",
	}, left)

	// And the directory the old package was in, since it held nothing else.
	_, err := os.Stat(filepath.Join(root, "old"))
	x.ErrorIs(err, fs.ErrNotExist)
}
