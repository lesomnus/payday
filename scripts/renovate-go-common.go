//go:build ignore

// Write the module names an app follows through payday, without prescribing
// versions: Go's minimum version selection still lets an app require newer ones.
// Run from the repository root; -check is the CI gate for a changed go.mod.
package main

import (
	"bytes"
	"encoding/json"
	"flag"
	"fmt"
	"os"
	"sort"

	"golang.org/x/mod/modfile"
)

type packageRule struct {
	Managers []string `json:"matchManagers"`
	Names    []string `json:"matchPackageNames"`
	Enabled  bool     `json:"enabled"`
}

func main() {
	check := flag.Bool("check", false, "fail if the committed preset is stale")
	flag.Parse()
	if err := run(*check); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}

func run(check bool) error {
	b, err := os.ReadFile("go.mod")
	if err != nil {
		return err
	}
	m, err := modfile.Parse("go.mod", b, nil)
	if err != nil {
		return err
	}
	names := make([]string, 0, len(m.Require))
	for _, r := range m.Require {
		names = append(names, r.Mod.Path)
	}
	sort.Strings(names)

	v := struct {
		Schema      string        `json:"$schema"`
		Description string        `json:"description"`
		Rules       []packageRule `json:"packageRules"`
	}{
		Schema:      "https://docs.renovatebot.com/renovate-schema.json",
		Description: "Generated by go run ./scripts/renovate-go-common.go from payday's go.mod. Apps follow these modules through payday upgrades; an app may require a newer version or override this rule locally.",
	}
	v.Rules = []packageRule{{Managers: []string{"gomod"}, Names: names}}
	b, err = json.MarshalIndent(v, "", "  ")
	if err != nil {
		return err
	}
	b = append(b, '\n')
	const path = "renovate/go-common.json"
	if check {
		old, err := os.ReadFile(path)
		if err != nil {
			return err
		}
		if !bytes.Equal(old, b) {
			return fmt.Errorf("%s is stale: run go run ./scripts/renovate-go-common.go", path)
		}
		return nil
	}
	return os.WriteFile(path, b, 0o644)
}
